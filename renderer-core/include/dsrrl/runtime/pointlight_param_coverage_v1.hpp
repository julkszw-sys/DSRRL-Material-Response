inline bool contains(std::uint64_t hash) noexcept
{
    std::size_t first = 0u;
    std::size_t last = k_row_name_hashes.size();
    while (first < last) {
        const auto mid = first + (last - first) / 2u;
        const auto value = k_row_name_hashes[mid];
        if (value < hash)
            first = mid + 1u;
        else
            last = mid;
    }
    return first < k_row_name_hashes.size() &&
           k_row_name_hashes[first] == hash;
}

